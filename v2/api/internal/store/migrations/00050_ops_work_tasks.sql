-- Công việc (bản Laravel: work_tasks): giao việc 2 chiều, nhiệm vụ hằng ngày của trợ giảng (kind = ta_daily) và việc
-- hệ thống tự giao (chăm sóc tháng đầu, duyệt đề Big Test, nhập bù hàng...). Một người nhận, trạng thái theo luồng
-- Mới → Đang thực hiện / Bị chặn → Chờ xác nhận → Hoàn thành; việc bị chặn chuyển lại được cho người giao (handed_back).
-- Schema ops dùng chung với báo cáo nhân sự, kho: không xóa schema ở Down.
-- +goose Up
CREATE SCHEMA IF NOT EXISTS ops;

CREATE TABLE ops.work_tasks (
    id                       uuid PRIMARY KEY DEFAULT uuidv7(),
    -- Số hiển thị "Công việc #N"; import từ Laravel giữ nguyên id cũ
    no                       bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    title                    text NOT NULL CHECK (length(title) BETWEEN 1 AND 255),
    description              text,
    -- Người giao (= người tạo)
    creator_id               uuid NOT NULL REFERENCES iam.users (id),
    assignee_id              uuid REFERENCES iam.users (id),
    -- Người đang làm khi việc bị chặn được chuyển lại cho người giao
    handed_back_from_id      uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    handed_back_at           timestamptz,
    branch_id                uuid REFERENCES core.branches (id) ON DELETE SET NULL,
    class_id                 uuid, -- FK tới academic.classes: 00110_academic_links_fk
    student_id               uuid, -- FK tới academic.students: 00110_academic_links_fk
    -- Mốc chăm sóc tháng đầu (ngày 3 / 7 / 14 / 30) của việc CRM tự tạo
    care_milestone           smallint CHECK (care_milestone > 0),
    big_test_id              uuid, -- FK tới syllabus.big_tests thêm khi gộp
    merchandise_item_id      uuid, -- FK tới ops.inventory_items thêm khi gộp
    -- Buổi học gắn với nhiệm vụ trợ giảng, vd. "Buổi 5 - Listening Practice (12/10)"
    lesson_session           text CHECK (length(lesson_session) <= 255),
    -- Ca trực của trợ giảng: Trước / Trong / Sau giờ học
    time_slot_category       text NOT NULL DEFAULT 'during' CHECK (time_slot_category IN ('before', 'during', 'after')),
    task_type                text NOT NULL DEFAULT 'one_time' CHECK (task_type IN ('one_time', 'recurring')),
    -- ta_daily: nhiệm vụ hằng ngày của trợ giảng, cố ý không có hạn (không bao giờ Quá hạn)
    kind                     text CHECK (kind IN ('ta_daily', 'merchandise_restock')),
    frequency                text CHECK (frequency IN ('daily', 'weekly', 'monthly')),
    due_date                 date,
    due_time                 time,
    status                   text NOT NULL DEFAULT 'new'
        CHECK (status IN ('new', 'in_progress', 'pending_confirmation', 'blocked', 'completed', 'overdue', 'canceled')),
    completion_note          text,
    -- Ảnh minh chứng: đường dẫn ảnh; khi có module tệp thì lưu thêm id tệp
    completion_proof_url     text CHECK (length(completion_proof_url) <= 2048),
    completion_proof_file_id uuid, -- FK tới core.files thêm khi gộp
    blocked_reason           text,
    rejection_reason         text,
    confirmed_by             uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    confirmed_at             timestamptz,
    completed_at             timestamptz,
    sla_breached_at          timestamptz,
    version                  integer NOT NULL DEFAULT 1,
    created_at               timestamptz NOT NULL DEFAULT now(),
    updated_at               timestamptz NOT NULL DEFAULT now()
);
-- Việc chăm sóc tháng đầu: mỗi học viên một việc cho mỗi mốc (lệnh tạo việc chạy lại không trùng)
CREATE UNIQUE INDEX work_tasks_student_care_key ON ops.work_tasks (student_id, care_milestone)
    WHERE student_id IS NOT NULL AND care_milestone IS NOT NULL;
CREATE INDEX work_tasks_assignee_idx ON ops.work_tasks (assignee_id, due_date);
CREATE INDEX work_tasks_creator_idx ON ops.work_tasks (creator_id, status);
CREATE INDEX work_tasks_branch_idx ON ops.work_tasks (branch_id);
CREATE INDEX work_tasks_pending_idx ON ops.work_tasks (updated_at) WHERE status = 'pending_confirmation';
-- Quét quá hạn: chỉ việc còn mở
CREATE INDEX work_tasks_open_due_idx ON ops.work_tasks (due_date) WHERE status IN ('new', 'in_progress');

-- +goose Down
DROP TABLE ops.work_tasks;
