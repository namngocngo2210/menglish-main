-- Test đầu vào & học thử (Laravel: placement_tests, placement_test_submissions, crm_trial_bookings).
-- - placement.tests: ngân hàng đề; câu hỏi + đáp án lưu JSONB (thí sinh không bao giờ nhận đáp án).
-- - placement.invitations: link mời làm bài công khai; chỉ lưu SHA-256 của token, có hạn, thu hồi được.
-- - placement.submissions: bài làm, điểm tự chấm (bản nháp) và kết quả chấm theo thang điểm khối lớp, nhật ký rời bài.
-- - crm.trial_bookings: buổi học thử của khách trong một buổi học thật; phân hệ này quản lý (schema crm của phân hệ CRM).
-- +goose Up
CREATE SCHEMA IF NOT EXISTS placement;
CREATE SCHEMA IF NOT EXISTS crm;

CREATE TABLE placement.tests (
    id               uuid PRIMARY KEY DEFAULT uuidv7(),
    -- Mã đề chứa khối lớp để chấm đúng thang điểm (TEST-G3-G4-...). Không trùng kể cả đề đã xóa (như Laravel).
    code             citext NOT NULL UNIQUE CHECK (length(code) BETWEEN 1 AND 50),
    title            text NOT NULL CHECK (length(title) BETWEEN 1 AND 255),
    description      text CHECK (length(description) <= 1000),
    target_level     text NOT NULL CHECK (length(target_level) <= 255),
    -- Cấp độ = lớp hiện tại của khách (mau_giao, lop_1..lop_9)
    grade_level      text CHECK (grade_level ~ '^(mau_giao|lop_[1-9])$'),
    duration_minutes integer NOT NULL CHECK (duration_minutes BETWEEN 1 AND 600),
    questions_count  integer NOT NULL DEFAULT 1 CHECK (questions_count >= 1),
    questions        jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(questions) = 'array'),
    -- Đề tạo từ PDF: đường dẫn file trong kho file (chưa dùng ở v2: chờ kho file chung)
    pdf_path         text CHECK (length(pdf_path) <= 255),
    audio_url        text CHECK (length(audio_url) <= 500),
    -- Ẩn = ngừng phát hành: mọi link mời của đề ngừng hoạt động
    is_active        boolean NOT NULL DEFAULT true,
    -- Đề mẫu hệ thống: khóa sửa / xóa, chỉ nhân bản
    is_preset        boolean NOT NULL DEFAULT false,
    created_by       uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    deleted_at       timestamptz,
    version          integer NOT NULL DEFAULT 1
);
CREATE INDEX tests_created_idx ON placement.tests (created_at DESC) WHERE deleted_at IS NULL;

CREATE TABLE placement.invitations (
    id               uuid PRIMARY KEY DEFAULT uuidv7(),
    test_id          uuid NOT NULL REFERENCES placement.tests (id),
    -- SHA-256 của token trong link; token gốc chỉ hiện một lần lúc tạo
    token_hash       bytea NOT NULL UNIQUE CHECK (length(token_hash) = 32),
    -- public: link phát hành chung của đề; lead: link riêng của một khách CRM
    kind             text NOT NULL CHECK (kind IN ('public', 'lead')),
    lead_id          uuid, -- FK tới crm.leads thêm khi gộp
    -- Thông tin điền sẵn trên trang làm bài (link riêng của khách)
    candidate_name   text CHECK (length(candidate_name) <= 255),
    candidate_phone  text CHECK (length(candidate_phone) <= 20),
    candidate_email  text CHECK (length(candidate_email) <= 255),
    note             text CHECK (length(note) <= 500),
    expires_at       timestamptz NOT NULL,
    -- Số lần nộp tối đa (NULL = không giới hạn, như link chung của Laravel)
    max_submissions  integer CHECK (max_submissions > 0),
    submission_count integer NOT NULL DEFAULT 0 CHECK (submission_count >= 0),
    opened_at        timestamptz,
    revoked_at       timestamptz,
    revoked_by       uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    created_by       uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CHECK ((kind = 'lead') = (lead_id IS NOT NULL))
);
CREATE INDEX invitations_test_idx ON placement.invitations (test_id, created_at DESC);
CREATE INDEX invitations_lead_idx ON placement.invitations (lead_id) WHERE lead_id IS NOT NULL;

CREATE TABLE placement.submissions (
    id                      uuid PRIMARY KEY DEFAULT uuidv7(),
    -- Số bài hiển thị cho người dùng ("bài #123"); import-legacy giữ nguyên id cũ
    number                  bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    test_id                 uuid NOT NULL REFERENCES placement.tests (id),
    invitation_id           uuid REFERENCES placement.invitations (id) ON DELETE SET NULL,
    lead_id                 uuid, -- FK tới crm.leads thêm khi gộp
    student_id              uuid, -- FK tới academic.students: 00110_academic_links_fk
    candidate_name          text NOT NULL CHECK (length(candidate_name) BETWEEN 1 AND 255),
    candidate_phone         text NOT NULL CHECK (length(candidate_phone) <= 20),
    candidate_email         text CHECK (length(candidate_email) <= 255),
    -- Khối lớp chấm theo thang điểm (khoi_1_2, khoi_2_3, khoi_3_4, khoi_4_5, khac)
    grade_group             text CHECK (grade_group IN ('khoi_1_2', 'khoi_2_3', 'khoi_3_4', 'khoi_4_5', 'khac')),
    listening_score         numeric(4, 1) CHECK (listening_score >= 0),
    reading_score           numeric(4, 1) CHECK (reading_score >= 0),
    writing_score           numeric(4, 1) CHECK (writing_score >= 0),
    speaking_score          numeric(4, 1) CHECK (speaking_score >= 0),
    reading_writing_score   numeric(4, 1) CHECK (reading_writing_score >= 0),
    overall_score           numeric(4, 1) CHECK (overall_score >= 0),
    total_score             numeric(4, 1) CHECK (total_score >= 0),
    cefr_level              text CHECK (length(cefr_level) <= 50),
    writing_content         text CHECK (length(writing_content) <= 5000),
    -- Câu trả lời theo id câu hỏi (+ speaking_self_rate)
    answers                 jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(answers) = 'object'),
    speaking_audio_url      text,
    recommended_course      text,
    teacher_comments        text CHECK (length(teacher_comments) <= 3000),
    suggested_class         text,
    chosen_class            text CHECK (length(chosen_class) <= 255),
    listening_comment       text CHECK (length(listening_comment) <= 3000),
    reading_writing_comment text CHECK (length(reading_writing_comment) <= 3000),
    speaking_comment        text CHECK (length(speaking_comment) <= 3000),
    grader_id               uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    graded_at               timestamptz,
    status                  text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'graded')),
    -- Khóa màn hình: số lần rời bài, nhật ký [{type, at}], bài bị tự nộp
    violation_count         integer NOT NULL DEFAULT 0 CHECK (violation_count BETWEEN 0 AND 1000),
    violation_log           jsonb CHECK (jsonb_typeof(violation_log) = 'array'),
    auto_submitted          boolean NOT NULL DEFAULT false,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    version                 integer NOT NULL DEFAULT 1
);
CREATE INDEX submissions_test_idx ON placement.submissions (test_id, created_at DESC);
CREATE INDEX submissions_created_idx ON placement.submissions (created_at DESC);
CREATE INDEX submissions_lead_idx ON placement.submissions (lead_id) WHERE lead_id IS NOT NULL;
CREATE INDEX submissions_pending_idx ON placement.submissions (status) WHERE status = 'pending';

CREATE TABLE crm.trial_bookings (
    id               uuid PRIMARY KEY DEFAULT uuidv7(),
    lead_id          uuid NOT NULL, -- FK tới crm.leads thêm khi gộp
    class_id         uuid NOT NULL, -- FK tới academic.classes: 00110_academic_links_fk
    class_session_id uuid NOT NULL, -- FK tới academic.class_sessions: 00110_academic_links_fk
    branch_id        uuid REFERENCES core.branches (id),
    -- Ngày giờ buổi học lúc xếp (để sắp lịch, lọc sắp tới / đã diễn ra); đổi lịch buổi học thì cập nhật theo
    session_date     date NOT NULL,
    start_time       time,
    end_time         time,
    status           text NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'attended', 'no_show', 'cancelled')),
    notes            text CHECK (length(notes) <= 3000),
    rating           smallint CHECK (rating BETWEEN 1 AND 5),
    -- Nhận xét theo đầu mục: grammar, attitude, result
    remarks          jsonb CHECK (jsonb_typeof(remarks) = 'object'),
    feedback         text CHECK (length(feedback) <= 3000),
    feedback_by      uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    feedback_at      timestamptz,
    booked_by        uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    version          integer NOT NULL DEFAULT 1,
    UNIQUE (lead_id, class_session_id)
);
CREATE INDEX trial_bookings_session_idx ON crm.trial_bookings (class_session_id, status);
CREATE INDEX trial_bookings_date_idx ON crm.trial_bookings (session_date, start_time);
CREATE INDEX trial_bookings_branch_idx ON crm.trial_bookings (branch_id, session_date);

