-- Chặng của lớp (syllabus_assignments), yêu cầu giãn tiến độ (syllabus_adjustment_requests), Big Test: đợt thi
-- (big_tests), order đề của giáo viên (big_test_orders), kết quả từng học viên (big_test_results).
-- Khóa ngoại chờ sẵn: academic.course_levels.syllabus_curriculum_id, ops.work_tasks.big_test_id.
-- +goose Up
CREATE SCHEMA IF NOT EXISTS syllabus;

-- Đợt Big Test của lớp; Big Test cuối chặng gắn stage_id.
CREATE TABLE syllabus.big_tests (
    id                   uuid PRIMARY KEY DEFAULT uuidv7(),
    -- BT-2026-0001 (DocumentCodeGenerator::bigTestCode)
    code                 text NOT NULL UNIQUE CHECK (length(code) BETWEEN 1 AND 50),
    title                text NOT NULL CHECK (length(title) BETWEEN 1 AND 255),
    class_id             uuid REFERENCES academic.classes (id) ON DELETE SET NULL,
    stage_id             uuid REFERENCES syllabus.stages (id) ON DELETE SET NULL,
    -- stage_end (cuối chặng), midterm, final…
    test_type            text NOT NULL DEFAULT 'midterm' CHECK (length(test_type) BETWEEN 1 AND 50),
    scheduled_at         timestamptz,
    room                 text CHECK (length(room) <= 255),
    proctor_id           uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    passcode             text CHECK (length(passcode) <= 50),
    content_url          text CHECK (length(content_url) <= 500),
    speaking_url         text CHECK (length(speaking_url) <= 500),
    is_distributed       boolean NOT NULL DEFAULT false,
    status               text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'distributed')),
    approved_by          uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    approved_at          timestamptz,
    distributed_at       timestamptz,
    -- Đã nhắc giáo viên lịch thi (bigtests:remind-upcoming nhắc một lần)
    teacher_reminded_at  timestamptz,
    -- Đã duyệt và gửi đủ kết quả cả lớp (dừng tính trễ hạn trả kết quả)
    results_completed_at timestamptz,
    created_by           uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX big_tests_class_idx ON syllabus.big_tests (class_id, scheduled_at DESC);
CREATE INDEX big_tests_stage_idx ON syllabus.big_tests (stage_id) WHERE stage_id IS NOT NULL;
CREATE INDEX big_tests_scheduled_idx ON syllabus.big_tests (scheduled_at) WHERE NOT is_distributed;

-- Chặng của lớp: mỗi lớp chỉ 1 chặng đang mở (in_progress); đóng khi Big Test của chặng được duyệt và gửi đủ phụ huynh.
CREATE TABLE syllabus.assignments (
    id                      uuid PRIMARY KEY DEFAULT uuidv7(),
    -- Số thứ tự cho mã hiển thị CH-<năm mở>-<số> (SyllabusAssignment::code)
    no                      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    -- Giáo viên phụ trách chặng
    user_id                 uuid NOT NULL REFERENCES iam.users (id) ON DELETE CASCADE,
    curriculum_id           uuid NOT NULL REFERENCES syllabus.curricula (id) ON DELETE CASCADE,
    stage_id                uuid REFERENCES syllabus.stages (id) ON DELETE SET NULL,
    class_id                uuid REFERENCES academic.classes (id) ON DELETE SET NULL,
    -- Phạm vi nội dung được giao: "Unit 1–3 · Buổi 1–12"
    assigned_chapters       text NOT NULL CHECK (length(assigned_chapters) <= 255),
    -- Tên chặng lúc mở (giữ khi chặng bị đổi tên / xóa)
    stage_name              text CHECK (length(stage_name) <= 255),
    deadline                date,
    expected_big_test_date  date,
    -- Đã nhắc order đề cho ngày dự kiến này (đổi ngày thì nhắc lại)
    big_test_reminded_for   date,
    progress_percent        integer NOT NULL DEFAULT 0 CHECK (progress_percent BETWEEN 0 AND 100),
    status                  text NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'completed')),
    opened_at               timestamptz,
    opened_by               uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    open_reason             text CHECK (length(open_reason) <= 2000),
    closed_at               timestamptz,
    closed_by               uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    close_reason            text CHECK (length(close_reason) <= 2500),
    closed_by_big_test_id   uuid REFERENCES syllabus.big_tests (id) ON DELETE SET NULL,
    curriculum_completed_at timestamptz,
    -- Số buổi giãn tiến độ đã duyệt cộng vào chặng
    extra_sessions          integer NOT NULL DEFAULT 0 CHECK (extra_sessions >= 0),
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now()
);
-- DB chặn chặng mở thứ hai của cùng lớp (thay cột open_class_id của Laravel)
CREATE UNIQUE INDEX assignments_one_open_uq ON syllabus.assignments (class_id) WHERE status = 'in_progress' AND class_id IS NOT NULL;
CREATE INDEX assignments_class_idx ON syllabus.assignments (class_id, status);
CREATE INDEX assignments_curriculum_idx ON syllabus.assignments (curriculum_id, stage_id);

-- Yêu cầu điều chỉnh (giãn) tiến độ của giáo viên, gắn chặng đang mở lúc gửi.
CREATE TABLE syllabus.pacing_requests (
    id               uuid PRIMARY KEY DEFAULT uuidv7(),
    class_id         uuid NOT NULL REFERENCES academic.classes (id) ON DELETE CASCADE,
    assignment_id    uuid REFERENCES syllabus.assignments (id) ON DELETE SET NULL,
    user_id          uuid NOT NULL REFERENCES iam.users (id) ON DELETE CASCADE,
    request_type     text NOT NULL CHECK (length(request_type) BETWEEN 1 AND 255),
    reason           text NOT NULL CHECK (length(reason) BETWEEN 1 AND 2000),
    extra_sessions   smallint CHECK (extra_sessions BETWEEN 0 AND 10),
    approver_id      uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    status           text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    rejection_reason text CHECK (length(rejection_reason) <= 2000),
    reviewed_at      timestamptz,
    -- Đã báo người duyệt quá hạn SLA (một lần)
    sla_notified_at  timestamptz,
    -- Kết quả áp dụng khi duyệt: buổi đã thêm, ngày kết thúc lớp mới
    applied_note     text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX pacing_requests_status_idx ON syllabus.pacing_requests (status, created_at DESC);
CREATE INDEX pacing_requests_user_idx ON syllabus.pacing_requests (user_id, created_at DESC);
CREATE INDEX pacing_requests_class_idx ON syllabus.pacing_requests (class_id);

-- Order đề test của giáo viên (Cổng GV) → Admin duyệt & phân phối kèm link đề, hoặc từ chối.
CREATE TABLE syllabus.big_test_orders (
    id               uuid PRIMARY KEY DEFAULT uuidv7(),
    -- ORDTEST-AB12CD
    code             text NOT NULL UNIQUE CHECK (length(code) BETWEEN 1 AND 50),
    class_id         uuid NOT NULL REFERENCES academic.classes (id) ON DELETE CASCADE,
    stage_id         uuid REFERENCES syllabus.stages (id) ON DELETE SET NULL,
    teacher_id       uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    stage_name       text NOT NULL CHECK (length(stage_name) BETWEEN 1 AND 255),
    test_type        text NOT NULL DEFAULT 'big' CHECK (test_type IN ('mini', 'big')),
    exam_date        date,
    -- Hạn xử lý: đề phải phân phối trước ngày thi N ngày (SLA big_test.paper_approval)
    due_date         date,
    note             text CHECK (length(note) <= 1000),
    status           text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    test_link        text CHECK (length(test_link) <= 500),
    speaking_link    text CHECK (length(speaking_link) <= 500),
    big_test_id      uuid REFERENCES syllabus.big_tests (id) ON DELETE SET NULL,
    reviewed_by      uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    reviewed_at      timestamptz,
    rejection_reason text CHECK (length(rejection_reason) <= 2000),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX big_test_orders_status_idx ON syllabus.big_test_orders (status, due_date);
CREATE INDEX big_test_orders_class_idx ON syllabus.big_test_orders (class_id, created_at DESC);

-- Kết quả Big Test từng học viên: Nháp → Chờ duyệt → Đã duyệt → Đã gửi phụ huynh.
CREATE TABLE syllabus.big_test_results (
    id              uuid PRIMARY KEY DEFAULT uuidv7(),
    big_test_id     uuid NOT NULL REFERENCES syllabus.big_tests (id) ON DELETE CASCADE,
    student_id      uuid NOT NULL REFERENCES academic.students (id) ON DELETE CASCADE,
    listening_score numeric(4, 1) CHECK (listening_score BETWEEN 0 AND 10),
    reading_score   numeric(4, 1) CHECK (reading_score BETWEEN 0 AND 10),
    writing_score   numeric(4, 1) CHECK (writing_score BETWEEN 0 AND 10),
    speaking_score  numeric(4, 1) CHECK (speaking_score BETWEEN 0 AND 10),
    overall_score   numeric(4, 1) CHECK (overall_score BETWEEN 0 AND 10),
    is_absent       boolean NOT NULL DEFAULT false,
    progress_note   text CHECK (length(progress_note) <= 2000),
    video_url       text CHECK (length(video_url) <= 500),
    status          text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'pending_review', 'approved', 'sent')),
    graded_by       uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    approved_by     uuid REFERENCES iam.users (id) ON DELETE SET NULL,
    approved_at     timestamptz,
    parent_notified boolean NOT NULL DEFAULT false,
    notified_at     timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (big_test_id, student_id)
);
CREATE INDEX big_test_results_student_idx ON syllabus.big_test_results (student_id);

